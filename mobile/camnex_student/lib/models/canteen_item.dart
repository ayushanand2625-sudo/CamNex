class CanteenItem {
  final String name;
  final String category;
  final int price;
  final int calories;
  final String counter;
  final int availableQty;
  final String status;

  CanteenItem({
    required this.name,
    required this.category,
    required this.price,
    required this.calories,
    required this.counter,
    required this.availableQty,
    required this.status,
  });
}