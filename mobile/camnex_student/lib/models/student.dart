class Student {
  final int id;

  String name;
  String studentClass;
  String admissionNo;

  double cardBalance;
  double feeDue;
  double attendance;

  Student({
    required this.id,
    required this.name,
    required this.studentClass,
    required this.admissionNo,
    required this.cardBalance,
    required this.feeDue,
    required this.attendance,
  });
}